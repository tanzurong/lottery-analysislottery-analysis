def parse_raw(lines):
    """把文本行解析为记录列表 [{period, red:[...], blue, demo}]。"""
    records = []
    for line in lines:
        t = line.strip()
        if not t or t.startswith("#"):
            continue
        parts = [p for p in re.split(r"[|,;\t ]+", t.strip()) if p]
        if len(parts) < 8:
            continue
        period = parts[0]
        nums = []
        ok = True
        for s in parts[-7:]:
            try:
                n = int(s)
            except ValueError:
                ok = False
                break
            nums.append(n)
        if not ok:
            continue
        red = sorted(nums[:6])
        blue = nums[6]
        if len(set(red)) != 6 or any(n < 1 or n > 33 for n in red):
            continue
        if blue < 1 or blue > 16:
            continue
        records.append({"period": period, "red": red, "blue": blue})
    return records
